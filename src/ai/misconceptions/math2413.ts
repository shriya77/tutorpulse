/** The misconceptions for a topic, flattened as "Section: item" lines for the prompt. */
export function misconceptionsFor(topic: string | undefined | null): string[] {
  // Only listed weeks: `topic in obj` would also match prototype keys like "constructor".
  if (!isTopicId(topic)) return []
  return MATH2413_MISCONCEPTIONS[topic].flatMap((s) => s.items.map((i) => `${s.title}: ${i}`))
}
